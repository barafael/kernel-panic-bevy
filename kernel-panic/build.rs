//! Embed the map and music catalogs at compile time.
//!
//! The web build has no filesystem to scan, and the native one ships
//! the same fixed set of maps, so `map_loading::pick_map` takes the
//! list of `.kpmap` files in `assets/maps/` from here on both. The
//! music player (`audio::music`) gets the same treatment for the `.ogg`
//! tracks in `assets/music/` (web only: native scans the folder, so a
//! player can drop tracks in).

use std::path::Path;

fn main() {
    catalog("assets/maps", "kpmap", "MAP_CATALOG", "map_catalog.rs");
    catalog(
        "assets/music",
        "ogg",
        "WEB_MUSIC_CATALOG",
        "web_music_catalog.rs",
    );
}

/// Write `OUT_DIR/<out_file>` defining `const_name` as the sorted file
/// stems of every `*.<ext>` in `dir` (relative to the crate root).
fn catalog(dir: &str, ext: &str, const_name: &str, out_file: &str) {
    println!("cargo:rerun-if-changed={dir}");

    let src_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join(dir);
    let mut names: Vec<String> = std::fs::read_dir(&src_dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|entry| {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) == Some(ext) {
                path.file_stem().map(|s| s.to_string_lossy().into_owned())
            } else {
                None
            }
        })
        .collect();
    names.sort();
    names.dedup();

    let entries: Vec<String> = names.iter().map(|n| format!("\"{n}\"")).collect();
    let generated = format!(
        "// @generated by build.rs — do not edit.\n\
         #[allow(dead_code)]\npub const {const_name}: &[&str] = &[{}];\n",
        entries.join(", ")
    );

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR set by cargo");
    let out_path = Path::new(&out_dir).join(out_file);
    std::fs::write(out_path, generated).expect("write web catalog");
}
